/**
 * Weekend risk report for lenders (Venus lists NVDAB/TSLAB/SPCXB with collateral factors 60/60/50%
 * but zero borrow caps). For each bStock with a public reference: one year of weekend/holiday gaps
 * (last close → next open), tail quantiles, worst case, and the solvency buffer a static collateral
 * factor leaves — plus how often Nightshift's dark-hours lower band was breached in the backtest.
 *
 *   pnpm exec tsx packages/nfv/src/venus-risk.ts   → docs/venus-weekend-risk.md
 */
import { writeFileSync } from "node:fs";
import { etParts } from "@nightshift/core";
import { loadUniverse } from "./data.ts";

const u = loadUniverse();
const NAMES = ["NVDA", "TSLA", "AAPL", "MSFT", "AMZN", "GOOGL", "META", "AVGO", "AMD", "TSM", "COIN", "MSTR", "HOOD", "CRCL", "PLTR", "MU", "SPY", "QQQ", "SMH", "SOXL"];
const VENUS_CF: Record<string, number> = { NVDA: 0.6, TSLA: 0.6 };

function quantile(xs: number[], p: number): number {
  const s = [...xs].sort((a, b) => a - b);
  const i = (s.length - 1) * p;
  const lo = Math.floor(i);
  const hi = Math.ceil(i);
  return s[lo]! + (s[hi]! - s[lo]!) * (i - lo);
}

const rows: string[] = [];
for (const t of NAMES) {
  const refs = u.ref.get(t);
  if (!refs || refs.length < 100) continue;
  const gaps: number[] = [];
  for (let k = 1; k < refs.length; k++) {
    const days = Math.round((refs[k]!.openTime - refs[k - 1]!.openTime) / 86_400_000);
    if (days < 2) continue; // weekends and holidays only: the dark gaps
    gaps.push(refs[k]!.open / refs[k - 1]!.close - 1);
  }
  if (gaps.length < 20) continue;
  const worst = Math.min(...gaps);
  const q01 = quantile(gaps, 0.01);
  const q05 = quantile(gaps, 0.05);
  const cf = VENUS_CF[t];
  // A position at the collateral factor stays solvent if collateral × (1 + gap) ≥ debt = collateral × CF.
  const buffer = cf ? 1 - cf : null;
  // Highest CF that would have stayed solvent through the worst weekend with a 5% liquidation bonus intact.
  const maxCf = (1 + worst) / 1.05;
  const first = etParts(refs[0]!.openTime).date;
  rows.push(
    `| ${t}B | ${gaps.length} | ${(q05 * 100).toFixed(2)}% | ${(q01 * 100).toFixed(2)}% | ${(worst * 100).toFixed(2)}% | ${(maxCf * 100).toFixed(0)}% | ${cf ? `${(cf * 100).toFixed(0)}% (buffer ${((buffer ?? 0) * 100).toFixed(0)}%)` : "—"} | ${first} |`,
  );
}

const md = `# Weekend risk report for lending against bStocks

*Generated by \`packages/nfv/src/venus-risk.ts\` from one year of official daily bars. Gap = next open ÷ last close − 1, over weekends and holidays (the dark hours).*

Venus Core Pool lists NVDAB and TSLAB (collateral factor 60%) and SPCXB (50%) but keeps **borrow caps at zero** because the oracle cannot price the weekend. The data below says **solvency is not the binding risk**: the worst weekend gap in a year is far inside a 40% buffer. The binding risk is the **oracle**. A feed that reports Friday's close all weekend prevents timely liquidations and invites oracle-gap attacks at the reopen. That is precisely what Nightshift fixes: a live fair value through the dark hours, plus a calibrated band for the next open that the risk engine can value collateral at.

| Collateral | Weekend/holiday gaps | 5% worst gap | 1% worst gap | Worst gap | Max CF solvent through worst gap (5% bonus) | Venus CF today |
|---|---|---|---|---|---|---|
${rows.join("\n")}

**How to turn borrowing on, with Nightshift:**
1. Read collateral prices from \`NightshiftVenusOracle\` (Venus \`OracleInterface\`), which returns Nightshift's consensus fair value and reverts when it is stale or a corporate action is flagged.
2. Outside the regular session, value collateral for *new borrows* at the report's \`lower\` (5th-percentile next-open price). This is what \`NightshiftCredit\` does on-chain.
3. Gate on band width: pause new borrows when \`(upper − lower)/fairValue\` exceeds the asset's normal dark-hours width (earnings, halts, news shocks).
4. Liquidations proceed through the weekend at fair value instead of waiting for Monday's gap.

Nightshift's dark-hours bands are calibrated out-of-sample: 86.6% coverage of the weekend-dark 90% band and 89.6% on holidays over every gap since bStocks listed (see \`docs/whitepaper.md\`).
`;
writeFileSync("docs/venus-weekend-risk.md", md);
console.log(md.split("\n").slice(6, 9 + rows.length).join("\n"));
