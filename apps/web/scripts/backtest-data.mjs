// Generates src/data/backtest.ts from research/study-v2.json (no hand-typed numbers).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..", "..");
const j = JSON.parse(readFileSync(join(root, "research", "study-v2.json"), "utf8"));
const order = [">40h", "16-40h", "6-16h", "1-6h", "≤1h"];
const byHorizon = order.map((b) => {
  let n = 0, s = 0, e = 0, v = 0, c = 0;
  for (const k of Object.keys(j)) {
    const p = k.split("|");
    if (p.length === 3 && p[1] === "hb" && p[2] === b) {
      const r = j[k];
      n += r.n; s += r.crps_stale_bps * r.n; e += r.crps_echo_bps * r.n; v += r.crps_v2_bps * r.n; c += r.cov90 * r.n;
    }
  }
  return { bucket: b, n, stale: +(s / n).toFixed(1), echo: +(e / n).toFixed(1), nfv: +(v / n).toFixed(1), cov90: +(c / n).toFixed(3) };
});
const data = { all: j.all, byHorizon, weekendDark: j["weekend|dark"], weekendRestart: j["weekend|restart"], overnight: j["overnight|live"], holidayDark: j["holiday|dark"] };
mkdirSync(join(import.meta.dirname, "..", "src", "data"), { recursive: true });
writeFileSync(
  join(import.meta.dirname, "..", "src", "data", "backtest.ts"),
  `/**\n * Out-of-sample backtest from research/study-v2.json: strict leave-one-gap-out over every gap since bStocks\n * listed, ${j.all.n.toLocaleString("en-US")} forecasts, Jun 11 to Oct 7 2026. CRPS in bps of price (lower is better).\n * byHorizon aggregates the per-session "hb" buckets, weighted by forecast count. Generated by scripts/backtest-data.mjs.\n */\nexport const BACKTEST = ${JSON.stringify(data, null, 2)} as const;\n`,
);
